// Builds data/project-display.json (+ public/projects/*.webp) for the project cards and details sheet.
// Deterministic, no network, no API keys. Inputs:
//   - projects.json and data/index.json (existing runtime data: ids, titles, live_url, period_display, skills)
//   - the portfolio evidence map HTML package (EVIDENCE_MAP=/path/to/html-package/index.html), matched by exact
//     GitHub repo name (case-insensitive) for full descriptions, named employers, skills and captured landing images.
// Missing facts are omitted (date) or use the approved fallback (company "consultant/Gig"); nothing is invented.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const MAP = process.env.EVIDENCE_MAP;
if (!MAP || !fs.existsSync(MAP)) { console.error("Set EVIDENCE_MAP to the evidence map html-package/index.html"); process.exit(1); }
const html = fs.readFileSync(MAP, "utf8");
const m = html.match(/<script type="application\/json" id="evidence-data">([\s\S]*?)<\/script>/);
if (!m) throw new Error("evidence-data block not found");
const ev = JSON.parse(m[1].replace(/<\\\//g, "</"));
const rows = new Map(ev.rows.map((r) => [r.n.toLowerCase(), r]));
const thumbs = ev.thumbnails.entries;

const { projects } = JSON.parse(fs.readFileSync("projects.json", "utf8"));
const idx = JSON.parse(fs.readFileSync("data/index.json", "utf8"));
const idxById = new Map(idx.projects.map((p) => [p.id, p]));
const chunkText = (id) => idx.chunks.filter((c) => c.project_id === id).map((c) => c.text).join("\n");

const FALLBACK_COMPANY = "consultant/Gig";
const out = {};
fs.mkdirSync("public/projects", { recursive: true });
for (const p of projects.filter((x) => x.allowed)) {
  const ip = idxById.get(p.id) || {};
  const repo = (p.repo || "").split("/").pop() || "";
  const row = repo ? rows.get(repo.toLowerCase()) || null : null;
  const liveUrl = ip.live_url || p.live_url || ip.figma_url || p.figma_url || null;

  const named = row && row.employer && row.employer.status === "named" ? row.employer.employer : null;
  const company = named || p.company || ip.company || null;

  let date = p.period_display || ip.period_display || null;
  if (!date) { const t = chunkText(p.id).match(/\bTimeline (\d{4}) (\d{4})\b/); if (t) date = `Timeline ${t[1]} – ${t[2]}`; }

  // Full description: evidence-map purpose only. Index summaries are cut at 220 chars by build-index.mjs, so they are not used.
  const summary = row && row.purpose ? row.purpose : null;
  const skills = row && row.skills && row.skills.length ? row.skills : p.skills || ip.skills || [];

  let image = null;
  const th = liveUrl && thumbs[liveUrl];
  if (th && th.status === "captured" && th.final) {
    const src = path.join(path.dirname(MAP), th.final);
    const dest = `public/projects/${p.id}.webp`;
    fs.copyFileSync(src, dest);
    image = { src: `/projects/${p.id}.webp`, alt: th.alt, width: th.width, height: th.height };
  }
  out[p.id] = {
    company: company || FALLBACK_COMPANY,
    companyKnown: !!company,
    date,
    summary,
    skills,
    liveUrl,
    image,
    evidenceRepo: row ? row.n : null,
  };
}
// Recent Work deployments (data/recent-work.json): matched to a runtime project by live URL, else to the evidence map
// through the captured URL's repo. The existing blurb stays the description unless a full evidence description exists.
const recentItems = JSON.parse(fs.readFileSync("data/recent-work.json", "utf8")).items;
const projByUrl = new Map(Object.entries(out).filter(([, v]) => v.liveUrl).map(([id, v]) => [v.liveUrl, { id, ...v }]));
const thumbFor = (url) => thumbs[url] || Object.values(thumbs).find((t) => (t.aliases || []).includes(url)) || null;
const recent = {};
fs.mkdirSync("public/recent", { recursive: true });
for (const it of recentItems) {
  const proj = projByUrl.get(it.url) || null;
  const th = thumbFor(it.url);
  const row = proj?.evidenceRepo ? rows.get(proj.evidenceRepo.toLowerCase()) : th?.repo ? rows.get(String(th.repo).toLowerCase()) || null : null;
  const named = row && row.employer && row.employer.status === "named" ? row.employer.employer : null;
  let image = null;
  if (proj?.image) image = proj.image;
  else if (th && th.status === "captured" && th.final) {
    fs.copyFileSync(path.join(path.dirname(MAP), th.final), `public/recent/${it.id}.webp`);
    image = { src: `/recent/${it.id}.webp`, alt: th.alt, width: th.width, height: th.height };
  }
  const company = proj ? (proj.companyKnown ? proj.company : null) : named;
  recent[it.id] = {
    company: company || FALLBACK_COMPANY,
    companyKnown: !!company,
    date: proj ? proj.date : null,
    summary: proj?.summary || (row && row.purpose) || it.blurb,
    skills: proj?.skills?.length ? proj.skills : row?.skills || [],
    liveUrl: it.url,
    image,
    evidenceRepo: row ? row.n : null,
    project: proj ? proj.id : null,
  };
}

const doc = {
  note: "Generated by scripts/build-project-display.mjs. Display-only fields for project cards; retrieval data is unchanged.",
  evidence_map_sha256: crypto.createHash("sha256").update(html).digest("hex"),
  evidence_map_generated: ev.generated || null,
  fallback_company: FALLBACK_COMPANY,
  projects: out,
  recent,
};
fs.writeFileSync("data/project-display.json", JSON.stringify(doc, null, 2) + "\n");
console.log(`project-display: ${Object.keys(out).length} projects, ${Object.values(out).filter((x) => x.evidenceRepo).length} matched to the evidence map, ${Object.values(out).filter((x) => x.image).length} images; recent: ${Object.keys(recent).length} items, ${Object.values(recent).filter((x) => x.image).length} images`);
